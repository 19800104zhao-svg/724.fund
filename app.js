function bindDemoEvents() {
  document.querySelectorAll("[data-filter]").forEach((button) => {
    button.addEventListener("click", () => {
      document.querySelectorAll("[data-filter]").forEach((item) => item.classList.toggle("active", item === button));
      renderOpportunityBoard(button.dataset.filter);
    });
  });

  document.addEventListener("click", (event) => {
    const target = event.target.closest("[data-action]");
    if (!target) return;
    const action = target.dataset.action;

    if (action === "sign-out") {
      event.preventDefault();
      demoState.loggedIn = false;
      demoState.role = "";
      demoState.userName = "";
      saveDemoState(demoState);
      renderAuthHeader();
      renderLoginPage();
      showToast("Signed out.");
      return;
    }

    if (action === "choose-role") {
      event.preventDefault();
      selectRole(target.dataset.role);
      return;
    }

    if (action === "demo-linkedin-login") {
      event.preventDefault();
      completeDemoLogin("linkedin", target.closest("form"));
      return;
    }

    if (action === "claim-opportunity") {
      const id = target.dataset.id;
      if (!demoState.claimed.includes(id)) demoState.claimed.push(id);
      const opportunity = opportunities.find((item) => item.id === id);
      addActivity(`Claimed AI search role: ${opportunity?.title || id}.`);
      saveDemoState(demoState);
      renderOpportunityBoard(document.querySelector("[data-filter].active")?.dataset.filter || "all");
      showToast("Role claimed. Added to Deal Room.");
    }

    if (action === "submit-intro") {
      const opportunity = opportunities.find((item) => item.id === target.dataset.id);
      demoState.introductions.unshift({
        id: `intro-${Date.now()}`,
        opportunity: opportunity?.title || "AI search role",
        person: "Consent-confirmed AI candidate",
        status: "Trust review",
        risk: "Low",
        note: "Demo candidate packet generated with consent and relationship proof."
      });
      addActivity(`Submitted candidate packet for ${opportunity?.title || "AI search role"}.`);
      saveDemoState(demoState);
      showToast("Candidate packet submitted for Trust Ops review.");
    }

    if (action === "connect-linkedin") {
      demoState.loggedIn = true;
      demoState.role = demoState.role || "connector";
      demoState.linkedinConnected = true;
      saveDemoState(demoState);
      renderLinkedInPage();
      renderAuthHeader();
      showToast("LinkedIn demo identity connected.");
    }

    if (action === "reset-linkedin") {
      demoState.linkedinConnected = false;
      demoState.networkContext = "";
      saveDemoState(demoState);
      renderLinkedInPage();
      showToast("LinkedIn demo reset.");
    }

    if (action === "review-decision") {
      demoState.reviews = demoState.reviews.filter((item) => item.id !== target.dataset.id);
      addActivity(`Trust review resolved: ${target.textContent}.`);
      saveDemoState(demoState);
      renderTrustOps();
      showToast("Review resolved and audit logged.");
    }

    if (action === "log-search-route") {
      addActivity(`Tom Agent logged talent search route: ${target.dataset.route}.`);
      renderActivityFeed();
      showToast("Search route logged for Trust Ops.");
    }
  });

  document.querySelectorAll("form[data-action]").forEach((form) => {
    form.addEventListener("submit", (event) => {
      event.preventDefault();
      const action = form.dataset.action;
      const data = new FormData(form);

      if (action === "demo-login") {
        completeDemoLogin("email", form);
      }

      if (action === "save-network") {
        demoState.networkContext = data.get("network") || "";
        saveDemoState(demoState);
        renderLinkedInPage();
        showToast("Network context saved locally.");
      }

      if (action === "send-message") {
        const to = data.get("to") || "Unspecified contact";
        addActivity(`Consent message logged for ${to}.`);
        renderActivityFeed();
        showToast("Consent message logged.");
      }

      if (action === "talent-search") {
        const query = String(data.get("query") || "").trim();
        demoState.lastTalentSearch = query;
        saveDemoState(demoState);
        renderTalentSearchResults(buildTalentSearch(query));
        addActivity("Tom Agent generated a natural-language AI talent search packet.");
        showToast("Talent search packet generated.");
      }

      if (action === "generate-brief") {
        const title = data.get("name") || "Untitled AI search mandate";
        const target = data.get("target") || "Candidate profile not specified";
        const reward = data.get("reward") || "Commission basis not specified";
        const payout = data.get("payout") || "Payout trigger not specified";
        const ownership = data.get("ownership") || "Candidate ownership not specified";
        const disqualifiers = data.get("disqualifiers") || "No disqualifiers provided";
        const briefTitle = document.getElementById("briefTitle");
        const briefOutput = document.getElementById("briefOutput");
        if (briefTitle) briefTitle.textContent = title;
        if (briefOutput) {
          briefOutput.textContent = `Candidate ICP: ${target}\nCommission basis: ${reward}\nPayout trigger: ${payout}\nCandidate ownership: ${ownership}\nAcceptance standard: direct relationship, candidate consent before reveal, specific fit reason.\nDisqualifiers: ${disqualifiers}\nTrust gates: owner authority, consent proof, duplicate candidate check, ownership conflict check, commission risk review.`;
        }
        addActivity(`Tom Agent generated AI search brief: ${title}.`);
        showToast("AI search brief generated.");
      }
    });
  });
}

