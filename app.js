function includesAny(text, words) {
  return words.some((word) => text.includes(word));
}

function inferTalentNeed(query) {
  const text = String(query || "").toLowerCase();
  const mustHaves = [];
  const disqualifiers = [];

  if (includesAny(text, ["japan", "tokyo", "日本", "东京", "東京"])) mustHaves.push("Japan or Tokyo market context");
  if (includesAny(text, ["bilingual", "日英", "english", "japanese", "双语", "バイリンガル"])) mustHaves.push("Bilingual communication");
  if (includesAny(text, ["llm", "rag", "retrieval", "agent", "eval", "ai infra", "生成式", "大模型"])) mustHaves.push("Production LLM / AI systems experience");
  if (includesAny(text, ["enterprise", "saas", "b2b", "客户", "エンタープライズ"])) mustHaves.push("Enterprise product or GTM exposure");
  if (includesAny(text, ["manage", "manager", "team", "lead", "leadership", "团队", "マネジメント"])) mustHaves.push("Senior team leadership");
  if (includesAny(text, ["startup", "founding", "cto", "founder", "创业", "創業"])) mustHaves.push("Startup operating judgment");

  if (includesAny(text, ["no cold", "不要冷", "cold outreach", "scrape", "爬取"])) disqualifiers.push("No cold list or scraped contact submission");
  if (includesAny(text, ["confidential", "stealth", "保密", "非公开"])) disqualifiers.push("Confidential mandate; anonymize owner before consent");

  const role = includesAny(text, ["cto", "技术合伙人", "founding"])
    ? "Founding CTO / AI technical leader"
    : includesAny(text, ["head", "vp", "director", "leader", "leadership", "负责人", "领导"])
      ? "Head of AI / senior AI leader"
      : includesAny(text, ["principal", "staff", "engineer", "工程师"])
        ? "Staff+ AI / ML engineer"
        : "Head of AI / senior AI leader";

  const geography = includesAny(text, ["japan", "tokyo", "日本", "东京", "東京"])
    ? "Japan / cross-border"
    : includesAny(text, ["us", "america", "美国", "cross-border", "跨境"])
      ? "Cross-border"
      : "Open geography";

  return {
    role,
    geography,
    seniority: includesAny(text, ["senior", "head", "vp", "cto", "principal", "staff", "高级", "负责人"]) ? "Senior / executive" : "Senior preferred",
    mustHaves: mustHaves.length ? mustHaves : ["Direct AI delivery experience", "Clear fit reason", "Connector can credibly reach the candidate"],
    disqualifiers: disqualifiers.length ? disqualifiers : ["No scraped LinkedIn list", "No full contact exposure before consent", "No vague relationship proof"]
  };
}

function scoreTalentPath(path, query) {
  const text = `${query} ${demoState.networkContext}`.toLowerCase();
  const matched = path.keywords.filter((keyword) => text.includes(keyword)).length;
  const contextBoost = demoState.networkContext ? 5 : 0;
  return Math.min(98, path.baseScore + matched * 3 + contextBoost);
}

function buildTalentSearch(query) {
  const need = inferTalentNeed(query);
  const rankedPaths = talentSearchPaths
    .map((path) => ({ ...path, score: scoreTalentPath(path, query) }))
    .sort((a, b) => b.score - a.score)
    .slice(0, 3);

  const searchTerms = [
    `("${need.role}" OR "VP AI" OR "AI Platform") AND ("${need.geography}" OR Tokyo) AND (LLM OR "AI product" OR "machine learning")`,
    `("Staff ML" OR "Principal ML" OR "AI infra") AND (Japan OR bilingual OR cross-border) AND (RAG OR evaluation OR retrieval)`,
    `("Head of AI" OR "AI Director" OR CTO) AND (startup OR enterprise) AND (Japan OR "APAC")`
  ];

  const outreach = [
    "Hi [Name], I came across a confidential senior AI leadership search that may fit your background.",
    "Before I share anything identifiable or introduce you, can I send a short anonymized brief and check whether you are open to this type of conversation?",
    "If it is not relevant, I will not disclose your name or contact details to the hiring side."
  ].join("\n\n");

  return {
    need,
    paths: rankedPaths,
    linkedinAssist: [
      "Manual LinkedIn search strings:",
      ...searchTerms.map((term, index) => `${index + 1}. ${term}`),
      "",
      "Review checklist:",
      "- Use LinkedIn only for manual profile inspection or identity context.",
      "- Do not scrape, export, automate messages, or store unauthorized member data.",
      "- Convert any possible match into a consent-first intro packet before owner review."
    ].join("\n"),
    outreach,
    audit: [
      ["Consent", "Candidate must opt in before identity or contact details are exposed."],
      ["Relationship proof", "Connector must state direct relationship, credible path, or trusted intermediary."],
      ["Duplicate check", "Normalize candidate/company/LinkedIn URL before owner review."],
      ["Ownership", "Check recruiter/search-firm ownership window before commission eligibility."],
      ["Ranking feedback", "Accepted/rejected owner decisions become future matching eval cases."]
    ]
  };
}

