const state = { lang: "en" };
const langButtons = document.querySelectorAll("[data-lang]");
const tabs = document.querySelectorAll(".tab");
const panels = document.querySelectorAll(".apply-form");
const summaryText = document.getElementById("summaryText");

function t(key) {
  return translations[state.lang][key] || translations.en[key] || key;
}

function applyLanguage(lang) {
  state.lang = translations[lang] ? lang : "en";
  document.documentElement.lang = state.lang === "zh" ? "zh-CN" : state.lang;

  document.querySelectorAll("[data-i18n]").forEach((element) => {
    element.textContent = t(element.dataset.i18n);
  });

  document.querySelectorAll("[data-i18n-placeholder]").forEach((element) => {
    element.setAttribute("placeholder", t(element.dataset.i18nPlaceholder));
  });

  langButtons.forEach((button) => {
    button.classList.toggle("active", button.dataset.lang === state.lang);
  });
}

function summarize(form) {
  const data = new FormData(form);
  const fallback = "-";

  if (form.dataset.panel === "connector") {
    return `${t("summary.connector")}: ${t("summary.name")} ${data.get("name") || fallback}; ${t("summary.domain")} ${data.get("domain") || fallback}; ${t("summary.network")} ${data.get("network") || fallback}; ${t("summary.contact")} ${data.get("contact") || fallback}. ${t("summary.review")}`;
  }

  return `${t("summary.publisher")}: ${t("summary.opportunity")} ${data.get("opportunity") || fallback}; ${t("summary.target")} ${data.get("target") || fallback}; ${t("summary.reward")} ${data.get("reward") || fallback}; ${t("summary.contact")} ${data.get("contact") || fallback}. ${t("summary.publisherReview")}`;
}

langButtons.forEach((button) => {
  button.addEventListener("click", () => {
    applyLanguage(button.dataset.lang);
    renderAuthHeader();
  });
});

tabs.forEach((tab) => {
  tab.addEventListener("click", () => {
    tabs.forEach((item) => item.classList.toggle("active", item === tab));
    panels.forEach((panel) => {
      panel.classList.toggle("active", panel.dataset.panel === tab.dataset.tab);
    });
  });
});

panels.forEach((form) => {
  form.addEventListener("submit", (event) => {
    event.preventDefault();
    summaryText.textContent = summarize(form);
  });
});

document.querySelectorAll("[data-copy-target]").forEach((button) => {
  button.addEventListener("click", async () => {
    const target = document.getElementById(button.dataset.copyTarget);
    if (!target) return;

    try {
      await navigator.clipboard.writeText(target.textContent.trim());
      button.textContent = t("summary.copied");
      setTimeout(() => {
        button.textContent = t("summary.copy");
      }, 1400);
    } catch {
      button.textContent = t("summary.manual");
    }
  });
});

